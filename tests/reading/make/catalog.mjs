// Draws one document's pages and named regions.
export async function draw(document) {
  if (document.stub) return payStubLayouts[document.stub.layout](document.stub, { twoPages: document.twoPages });
  if (document.gig)
    return document.gig.monthly
      ? gigMonthly(document.gig, { twoPages: document.twoPages })
      : gigWeekly(document.gig);
  if (document.sheet)
    return volunteerSheet({
      ...document.sheet,
      rows: document.sheet.rows.map(([date, timeIn, timeOut, hours, task]) => ({
        date,
        in: timeIn,
        out: timeOut,
        hours,
        task,
        staff: document.sheet.staff,
      })),
    });
  if (document.school) return classSchedule(document.school);
  if (document.letter) return enrollmentLetter(document.letter);
  if (document.notice) return stateNotice(document.notice);
  if (document.foreign) return foreignPaySlip(document.foreign);
  if (document.receipt) return receipt(document.receipt);
  if (document.note) return instructionNote(document.note);
  throw new Error(`No drawing for ${document.id}`);
}

export const fileName = (document) => `${document.id}.${document.format}`;
