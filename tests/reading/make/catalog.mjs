// A pay stub with its totals, taxes and year-to-date figures worked out from the lines.
export function payStub(spec) {
  const earnings = spec.earnings.map(([label, hours, rateCents, fixedCents]) => ({
    label,
    hours,
    rateCents,
    cents: fixedCents ?? Math.round(hours * rateCents),
  }));
  const gross = earnings.reduce((sum, line) => sum + line.cents, 0);
  const pretax = (spec.pretax ?? []).map(([label, cents]) => ({ label, cents }));
  const pretaxTotal = pretax.reduce((sum, line) => sum + line.cents, 0);
  const taxable = gross - pretaxTotal;
  const taxNames =
    spec.language === "es"
      ? ["Impuesto federal", "Seguro Social", "Medicare", "Impuesto estatal"]
      : ["Federal income tax", "Social Security", "Medicare", "State income tax"];
  const taxes = [0.07, 0.062, 0.0145, spec.stateRate ?? 0.03].map((rate, i) => ({
    label: taxNames[i],
    cents: Math.round(taxable * rate),
  }));
  const taxTotal = taxes.reduce((sum, line) => sum + line.cents, 0);
  const after = (spec.after ?? []).map(([label, cents]) => ({ label, cents }));
  const afterTotal = after.reduce((sum, line) => sum + line.cents, 0);
  const periods = spec.periodsToDate;
  const withYtd = (lines) => lines.map((line) => ({ ...line, ytd: line.cents * periods }));
  const hoursLines = earnings.filter((line) => line.hours != null);
  const stub = {
    ...spec,
    earnings: withYtd(earnings),
    pretax: withYtd(pretax),
    taxes: withYtd(taxes),
    after: withYtd(after),
    gross,
    pretaxTotal,
    taxTotal,
    afterTotal,
    net: gross - pretaxTotal - taxTotal - afterTotal,
    hoursTotal: hoursLines.length ? Math.round(hoursLines.reduce((sum, line) => sum + line.hours, 0) * 100) / 100 : null,
  };
  stub.ytd = {
    gross: gross * periods,
    pretax: pretaxTotal * periods,
    taxes: taxTotal * periods,
    after: afterTotal * periods,
    net: stub.net * periods,
  };
  return stub;
}

// A gig summary with gross, fees and net worked out from the lines.
export function gig(spec) {
  const lines = spec.lines.map(([label, cents]) => ({ label, cents }));
  const value = { ...spec, lines, fees: spec.fees.map(([label, cents]) => ({ label, cents })) };
  value.gross = lines.reduce((sum, line) => sum + line.cents, 0);
  value.feeTotal = value.fees.reduce((sum, line) => sum + line.cents, 0);
  value.net = value.gross - value.feeTotal;
  if (spec.weekSplit) {
    const shares = spec.weekSplit.shares;
    value.weeks = spec.weekSplit.weeks.map(([start, end]) => ({
      start,
      end,
      count: 0,
      cents: lines.map(() => 0),
    }));
    let countLeft = spec.count;
    const left = lines.map((line) => line.cents);
    shares.forEach((share, index) => {
      const last = index === shares.length - 1;
      const week = value.weeks[index];
      week.count = last ? countLeft : Math.round(spec.count * share);
      countLeft -= week.count;
      week.cents = lines.map((line, i) => {
        const cents = last ? left[i] : Math.round(line.cents * share);
        left[i] -= cents;
        return cents;
      });
    });
  }
  return value;
}

